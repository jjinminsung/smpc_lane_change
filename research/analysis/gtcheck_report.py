def pct(x, d=1):
    return "n/a" if x is None else ("%." + str(d) + "f%%") % (100.0 * x)


def f2(x, d=2):
    return "n/a" if x is None or (isinstance(x, float) and not np.isfinite(x)) else ("%." + str(d) + "f") % x


def ref_impact(c_car, c_long):
    """Rear/front bumper gaps on object-mode targets, centre vs measured reference."""
    out = {"rear_lc": 0, "rear_cross_9m": 0, "rear_in_9_15": 0, "front_lc": 0, "front_cross_14m": 0,
           }
    for lab in BAGS:
        R = gc.extract_targets(os.path.join(gc.REPLAY_DIR, lab + ".bag"))
        d = bt.load_bag(os.path.expanduser("~/bags/lc_gt_%s.bag" % lab))
        win = ga.in_windows(R["t"], ga.lc_windows(d))
        V = R["target_rear"]
        m = win & (V["valid"] > 0)
        c = np.where(V["length"] >= 7.0, c_long, c_car)
        g = -V["front_delta_s"] - 0.790
        gc_ = g - c
        out["rear_lc"] += int(m.sum())
        out["rear_cross_9m"] += int(np.sum(m & (g >= 9.0) & (gc_ < 9.0)))
        out["rear_in_9_15"] += int(np.sum(m & (g >= 9.0) & (g < 15.0)))
        F = R["target_front"]
        m = win & (F["valid"] > 0)
        c = np.where(F["length"] >= 7.0, c_long, c_car)
        gf = F["rear_delta_s"] - 3.845
        out["front_lc"] += int(m.sum())
        out["front_cross_14m"] += int(np.sum(m & (gf < 14.0) & (gf + c >= 14.0)))
    return out


